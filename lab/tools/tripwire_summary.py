"""Builds a cross-version summary table from results/tripwire_emulator.csv. Standard library only.

Several runs per Android version exist because the harness had bugs that were found and fixed (see DEFECT_LOG.md).
For each version this picks the LATEST COMPLETE run, and it marks a cell as 'not exercised' when the event it is meant
to test did not really happen (for example the fingerprint test when the second fingerprint never registered), so a
cell can never claim more than the run measured.

    python tools/tripwire_summary.py            # prints markdown and writes results/tripwire_summary.md
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
LAB = os.path.dirname(HERE)
CSV_PATH = os.path.join(LAB, "results", "tripwire_emulator.csv")
OUT_PATH = os.path.join(LAB, "results", "tripwire_summary.md")

START = "A baseline (1 fingerprint): create keys"


def split_runs(rows):
    """Split rows (in file order) into runs; a new run starts at each baseline-create row."""
    runs, current = [], []
    for r in rows:
        if r["step"].startswith(START) and current:
            runs.append(current)
            current = []
        current.append(r)
    if current:
        runs.append(current)
    return runs


def is_complete(run):
    return any(r["step"].startswith("K7c") for r in run) and any(r["step"].startswith("K6") for r in run)


def find(run, prefix):
    for r in run:
        if r["step"].startswith(prefix):
            return r
    return None


def short(state):
    """Compress a key-state string for the table."""
    if not state:
        return "no answer"
    if state.startswith("CREATE_FAILED"):
        if "Secure lock screen" in state:
            return "refused (needs lock)"
        if "biometric must be enrolled" in state:
            return "refused (needs fingerprint)"
        if "Failed to delete entry" in state:
            return "failed (stale key)"
        return "refused"
    if state.startswith("OTHER:"):
        return "unusable (" + state.split(":")[1] + ")"
    return state.lower()


def cell(run, prefix, which, needs_two_fingerprints=False):
    r = find(run, prefix)
    if r is None:
        return "no data"
    value = short(r[which])
    if needs_two_fingerprints and int(r["enrolled_fingerprints"] or 0) < 2:
        return f"NOT EXERCISED ({value}, only {r['enrolled_fingerprints']} fingerprint)"
    return value


def summarize(rows):
    """Return {api: {column: text}} using the latest complete run per API."""
    by_api = {}
    for r in rows:
        by_api.setdefault(r["api"], []).append(r)
    out = {}
    for api, api_rows in by_api.items():
        runs = [run for run in split_runs(api_rows) if is_complete(run)]
        if not runs:
            out[api] = None
            continue
        run = runs[-1]
        bio, any_ = "key_biometric_only", "key_biometric_or_credential"
        out[api] = {
            "runs_complete": len(runs),
            "fingerprint added: biometric-only key": cell(run, "K6", bio, True),
            "fingerprint added: biometric-or-PIN key": cell(run, "K6", any_, True),
            "app reinstalled": cell(run, "S after reinstalling", bio),
            "device rebooted": cell(run, "S after reboot", bio),
            "PIN changed": cell(run, "K7a", bio),
            "lock removed": cell(run, "K7b", bio),
            "create keys with no lock": cell(run, "K7c", any_),
        }
    return out


def to_markdown(summary):
    cols = ["fingerprint added: biometric-only key", "fingerprint added: biometric-or-PIN key", "app reinstalled",
            "device rebooted", "PIN changed", "lock removed", "create keys with no lock"]
    lines = ["| API | Android | " + " | ".join(cols) + " |", "|" + "---|" * (len(cols) + 2)]
    names = {"29": "10", "31": "12", "33": "13", "34": "14", "35": "15", "36": "16", "37": "17"}
    for api in sorted(summary, key=lambda a: int(a)):
        s = summary[api]
        if s is None:
            lines.append(f"| {api} | {names.get(api, '?')} | " + " | ".join(["no complete run"] * len(cols)) + " |")
        else:
            lines.append(f"| {api} | {names.get(api, '?')} | " + " | ".join(s[c] for c in cols) + " |")
    return "\n".join(lines)


def main():
    with open(CSV_PATH, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    md = to_markdown(summarize(rows))
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("# Tripwire experiment summary (emulator only)\n\nLatest complete run per Android version. "
                "Generated by tools/tripwire_summary.py.\n\n" + md + "\n")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
